#!/usr/bin/env python3
"""Runner for the multi-threaded bespoke TPC-H / CEB implementations.

Unlike ``run.py`` (which drives the single-threaded variants through the
``bespoke-olap`` plugin/FastTest harness), the multi-threaded artifacts in
``bespoke_tpch_multithreading/`` and ``bespoke_ceb_multithreading/`` are a
self-contained engine with a different driver contract:

  * No ``main``/stdin driver ships with them.
  * The query entry point is
    ``std::vector<QueryResult> query(Database*, const std::vector<std::string>&)``
    (line-based), not the harness's ``void query(Database*)``.
  * A few headers the sources ``#include`` are not present in the tree
    (``trace.hpp``) or do not define everything the sources use
    (``query_api.hpp`` is expected to define ``QueryResult``).

So this runner does not reuse the plugin machinery. It:
  1. Generates query instantiations with the same generator ``run.py`` uses.
  2. Writes three small shim files into the source dir's ``build_mt/`` folder:
     ``trace.hpp``, ``query_api.hpp`` and a ``main.cpp`` driver.
  3. Compiles every implementation ``.cpp`` (excluding the ``*_api.cpp``
     plugin wrappers, which are bypassed) together with the driver into one
     executable linked against Arrow/Parquet.
  4. Runs the executable, feeding the generated query lines on stdin. The
     engine writes per-query results to ``results/result<N>.csv`` in the
     source directory.

Platform note: the multi-threaded engine targets Linux. ``cpu_affinity.cpp``
uses ``<sched.h>``/``sched_setaffinity`` and will not compile on macOS. Arrow
and Parquet must be discoverable via ``pkg-config``.
"""

import argparse
import logging
import os
import random
import shutil
import subprocess
import sys
from pathlib import Path

from benchmark.run import get_all_query_ids
from dataset.query_gen_factory import get_query_gen
from llm_cache.logger import setup_logging
from tools.validate_tool.query_validator_class import format_args_string

BASE_PARQUET_DIR = "/mnt/labstore/bespoke_olap"

# The multi-threaded parquet dirs use the same dataset naming as the
# single-threaded ones (tpch -> tpch, ceb -> imdb). Keep an explicit map so the
# runner does not depend on import side effects.
DATASET_NAME = {"tpch": "tpch", "ceb": "imdb"}

setup_logging(logging.INFO)
logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Query instantiation (same approach as run.py)
# ---------------------------------------------------------------------------
def get_args_lines(benchmark: str, repeat: int = 1) -> list[str]:
    """Return one ``"<qid> \"v1\" \"v2\" ..."`` line per query instantiation."""
    gen_query_fn = get_query_gen(benchmark)
    query_ids = get_all_query_ids(benchmark)

    query_list: list[str] = []
    placeholder_list: list[dict] = []

    rnd = random.Random(42)
    for _ in range(repeat):
        for query_id in query_ids:
            _template, _query, placeholders = gen_query_fn(
                query_name=f"Q{query_id}", rnd=rnd
            )
            query_list.append(str(query_id))
            placeholder_list.append(placeholders)

    return format_args_string(query_list, placeholder_list)


# ---------------------------------------------------------------------------
# Shim files the multi-threaded sources assume but do not ship
# ---------------------------------------------------------------------------
TRACE_HPP = """// Generated by run_mt.py.
// Minimal no-op trace facility. The multi-threaded sources include "trace.hpp"
// and use PROFILE_SCOPE / TRACE_RESET / TRACE_FLUSH / TRACE_COUNT, but no such
// header ships with the artifacts. These no-ops let the engine build and run
// without tracing. Replace with a real implementation to collect stats.
#pragma once

#define PROFILE_SCOPE(name) ((void)0)
#define TRACE_RESET() ((void)0)
#define TRACE_FLUSH() ((void)0)
#define TRACE_COUNT(name, n) ((void)0)
"""

QUERY_API_HPP = """// Generated by run_mt.py.
// The multi-threaded query_impl.hpp includes "query_api.hpp" and uses
// QueryResult, but the harness header that ships with bespoke-olap only
// declares the single-threaded plugin API. This shim provides the type the
// line-based query() entry point actually returns.
#pragma once

#include <string>

struct Database;

struct QueryResult {
    std::string message;   // optional per-query message (unused by the engine)
    long long elapsed_ms;  // wall-clock time for the query, -1 if not measured
};

std::vector<QueryResult> query(Database*, const std::vector<std::string>& query_lines);
"""

MAIN_CPP = """// Generated by run_mt.py.
// Standalone driver for the multi-threaded bespoke engine. Loads the parquet
// tables, builds the in-memory database, reads query lines from stdin (one per
// line, same format run.py feeds the single-threaded harness), runs them and
// reports per-query timings on stderr. Per-query result rows are written by the
// engine to results/result<N>.csv in the current working directory.
#include "parquet_reader.hpp"   // load / destroy_parquet_tables, ParquetTables
#include "db_loader.hpp"        // build / destroy_database, Database
#include "query_api.hpp"        // query(), QueryResult

#include <chrono>
#include <iostream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc < 2) {
        std::cerr << "Usage: " << argv[0] << " <PARQUET_DIR>\\n";
        return 1;
    }
    std::string parquet_dir = argv[1];

    std::cerr << "loader start (" << parquet_dir << ")\\n";
    ParquetTables* tables = load(parquet_dir);
    std::cerr << "loader done\\n";

    std::cerr << "builder start\\n";
    const auto t0 = std::chrono::steady_clock::now();
    Database* db = build(tables);
    const auto t1 = std::chrono::steady_clock::now();
    std::cerr << "builder done (ingest ms: "
              << std::chrono::duration<double, std::milli>(t1 - t0).count()
              << ")\\n";

    std::vector<std::string> query_lines;
    std::string line;
    while (std::getline(std::cin, line)) {
        if (line.empty()) continue;  // blank line = end-of-input sentinel
        query_lines.push_back(line);
    }
    std::cerr << "query start (" << query_lines.size() << " queries)\\n";

    const auto q0 = std::chrono::steady_clock::now();
    std::vector<QueryResult> results = query(db, query_lines);
    const auto q1 = std::chrono::steady_clock::now();
    std::cerr << "query done (total ms: "
              << std::chrono::duration<double, std::milli>(q1 - q0).count()
              << ")\\n";

    for (std::size_t i = 0; i < results.size(); ++i) {
        std::cerr << "  query " << (i + 1) << ": " << results[i].elapsed_ms
                  << " ms\\n";
    }

    destroy_database(db);
    destroy_parquet_tables(tables);
    return 0;
}
"""


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
# Plugin wrapper files: bypassed by the standalone driver, which calls the
# load/build/query implementations directly. Skipping them avoids pulling in
# utils/plugin_base.hpp and duplicate plugin_query symbols.
EXCLUDED_CPP = {"builder_api.cpp", "loader_api.cpp"}


def pkg_config(args: list[str]) -> list[str]:
    try:
        out = subprocess.run(
            ["pkg-config", *args],
            check=True,
            text=True,
            capture_output=True,
        ).stdout
    except FileNotFoundError:
        raise SystemExit("pkg-config not found; install it to locate Arrow/Parquet.")
    except subprocess.CalledProcessError as exc:
        raise SystemExit(
            f"pkg-config {' '.join(args)} failed:\n{exc.stderr.strip()}\n"
            "Make sure the Arrow and Parquet development packages are installed."
        )
    return out.split()


def build(src_dir: Path, optimize: bool) -> Path:
    build_dir = src_dir / "build_mt"
    build_dir.mkdir(exist_ok=True)

    # Write shim files into the build dir and add it to the include path.
    (build_dir / "trace.hpp").write_text(TRACE_HPP)
    (build_dir / "query_api.hpp").write_text(QUERY_API_HPP)
    main_cpp = build_dir / "main.cpp"
    main_cpp.write_text(MAIN_CPP)

    srcs = sorted(
        p for p in src_dir.glob("*.cpp") if p.name not in EXCLUDED_CPP
    )
    srcs.append(main_cpp)

    cxx = os.environ.get("CXX", "g++")
    cxxflags = ["-std=c++20", "-pthread", f"-I{src_dir}", f"-I{build_dir}"]
    cxxflags += ["-O3"] if optimize else ["-O0"]
    cxxflags += pkg_config(["--cflags", "arrow", "parquet"])
    ldflags = pkg_config(["--libs", "arrow", "parquet"])

    out = build_dir / "db_mt"
    cmd = [cxx, *cxxflags, *[str(s) for s in srcs], "-o", str(out), *ldflags]

    logger.info("Compiling %d sources -> %s", len(srcs), out)
    logger.debug("Compile command: %s", " ".join(cmd))
    proc = subprocess.run(cmd, text=True, capture_output=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"Compilation failed ({cxx} returned {proc.returncode}).")
    return out


# ---------------------------------------------------------------------------
# Run
# ---------------------------------------------------------------------------
def run(executable: Path, parquet_dir: str, args_lines: list[str], cwd: Path) -> None:
    stdin_data = "".join(line + "\n" for line in args_lines) + "\n"  # trailing sentinel
    logger.info("Running %s %s with %d queries", executable, parquet_dir, len(args_lines))
    proc = subprocess.run(
        [str(executable), parquet_dir],
        input=stdin_data,
        text=True,
        cwd=cwd,
    )
    if proc.returncode != 0:
        raise SystemExit(f"Engine exited with code {proc.returncode}.")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build and run the multi-threaded bespoke OLAP implementation."
    )
    parser.add_argument(
        "benchmark", choices=["tpch", "ceb"], help="Which benchmark to run"
    )
    parser.add_argument("--sf", type=float, default=1, help="Scale factor (default: 1)")
    parser.add_argument(
        "--no-optimize",
        dest="optimize",
        help="Compile without -O3",
        action="store_false",
        default=True,
    )
    parser.add_argument(
        "--parquet-dir",
        default=None,
        help="Override parquet base dir (default: %s/<dataset>_parquet)" % BASE_PARQUET_DIR,
    )
    parser.add_argument(
        "--build-only",
        action="store_true",
        help="Compile the engine but do not run it",
    )
    args = parser.parse_args()

    sf = int(args.sf) if args.sf >= 1 and float(args.sf).is_integer() else args.sf

    root = Path(__file__).parent
    src_dir = root / f"bespoke_{args.benchmark}_multithreading"
    if not src_dir.is_dir():
        raise SystemExit(f"Source directory not found: {src_dir}")

    if os.environ.get("CXX", "g++") in ("g++", "gcc") and not shutil.which("g++"):
        raise SystemExit("g++ not found; set CXX or install a C++20 compiler.")

    logger.info(
        "Building multi-threaded %s (optimize=%s)...", args.benchmark, args.optimize
    )
    executable = build(src_dir, optimize=args.optimize)

    if args.build_only:
        logger.info("Build complete: %s", executable)
        return

    base = args.parquet_dir or f"{BASE_PARQUET_DIR}/{DATASET_NAME[args.benchmark]}_parquet"
    parquet_dir = f"{base}/sf{sf}/"

    args_lines = get_args_lines(benchmark=args.benchmark, repeat=1)
    run(executable, parquet_dir, args_lines, cwd=src_dir)

    logger.info("Finished. Result CSVs written to %s/results/", src_dir)


if __name__ == "__main__":
    main()
